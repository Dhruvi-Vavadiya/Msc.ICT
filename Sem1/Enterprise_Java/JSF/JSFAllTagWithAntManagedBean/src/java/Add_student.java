//1st page 
public class Add_student {
    private String name;
    private String SClass;
    private String rno;
    private int age;

    public Add_student(String name, String SClass, String rno, int age) {
        this.name = name;
        this.SClass = SClass;
        this.rno = rno;
        this.age = age;
    }

    
    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getSClass() {
        return SClass;
    }

    public void setSClass(String SClass) {
        this.SClass = SClass;
    }

    public String getRno() {
        return rno;
    }

    public void setRno(String rno) {
        this.rno = rno;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }
    
    
    
}
